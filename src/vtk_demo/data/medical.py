    return DataSet(
        name=name,
        location=slicer(file_name, sha256, size),
        metadata=MetaData(
            author=AUTHOR,
            license=License.UNKNOWN,
            description=description,
            tags=tags,
            reference=SLICER_DATA_STORE,
        ),
    )


